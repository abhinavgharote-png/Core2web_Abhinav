//Program to add, subtract, multiply, and divide given digits

#include<stdio.h>

int main()
{
	int num1=2;
	int num2=100;
	
	printf("2 + 100 = %d\n", num1+num2);
	printf("2 - 100 = %d\n", num1-num2);
	printf("2 x 100 = %d\n", num1*num2);
	printf("2 / 100 = %d\n", num1/num2);
	printf("2 %% 100 = %d", num1%num2);
	
	return 0;
	
}

